"""HashHop — long-context multi-hop key/value retrieval.

The benchmark is Magic AI's HashHop, generated by the
`hashhop <https://github.com/codelion/hash-hop>`_ package. Each instance
contains a chain of ``N`` hash assignments::

    h0 = h1
    h1 = h2
    ...
    h(N-1) = 'hN'      # quoted = terminal

mixed in among many other independent chains, all serialized as a
shuffled dictionary. The model must start from ``h0`` and report the
terminal hash ``hN`` after walking ``N`` lookups.

Random guessing on 16-character mixed-case hashes is effectively zero
(52^16), so accuracy maps cleanly to how reliably the model is using
its long-context KV cache for needle-in-a-haystack retrieval through
``N`` indirections. We probe ``hops=1..4`` with 25 instances each
(100 total).

Why this matters for OptiQ vs uniform-4-bit: uniform 4-bit quantization
of weights erodes long-range attention precision (small numerical errors
compound across many heads × many tokens). Sensitivity-aware mixed
precision keeps the layers that matter for retrieval at 8-bit, so the
gap on multi-hop is wider than on single-shot tasks like MMLU.
"""

from __future__ import annotations

import os
import random
import re
from ._harmony import strip_to_final_channel, concise_template_kwargs
import time
from dataclasses import dataclass

import numpy as np


_DEFAULT_HOPS = (1, 2, 3, 4)
_INSTANCES_PER_HOP = 25
_HASH_LEN = 16
_DEFAULT_CHARS = 12000
_MAX_NEW_TOKENS = 512  # standardized non-reasoning budget (the answer is a 16-char hash; the model stops early)


_INSTR = (
    "You will be given a list of hash assignments and a starting hash. "
    "Walk the chain by repeated key->value lookup until you hit a "
    "terminal value (written with single quotes, e.g. `KEY = 'VALUE'`). "
    "Output ONLY the final 16-character hash inside the quotes, with "
    "no extra words or punctuation."
)


@dataclass
class HashHopResult:
    """Per-hop and overall accuracy on the HashHop benchmark."""

    overall_acc: float                    # 0..1, simple mean over all instances
    by_hops: dict[int, float]             # hops -> accuracy (0..1)
    n_per_hops: int
    hops_list: tuple[int, ...]
    chars_per_problem: int
    context_tokens_observed: int          # average over first few samples
    elapsed_sec: float

    def __str__(self) -> str:
        lines = [
            f"HashHop overall: {self.overall_acc * 100:.1f}% "
            f"({self.n_per_hops} per hop × {len(self.hops_list)} hop levels, "
            f"~{self.context_tokens_observed} ctx tokens, "
            f"elapsed {self.elapsed_sec:.0f}s)"
        ]
        for h in self.hops_list:
            v = self.by_hops.get(h, 0.0)
            lines.append(f"  hops={h:>2}  {v * 100:>5.1f}%")
        return "\n".join(lines)


def _format_prompt(sample) -> tuple[str, str, str]:
    """Pick the first (query, target) from a MultiHopEval sample and
    build the prompt.

    Returns ``(prompt_text, query, expected_final_hash)``.
    """
    query, target_str = next(iter(sample.targets.items()))
    # Without chain_of_thought the target is just the final hash; with
    # CoT it would be "h1 = h2 = ... = hN" — take the last segment.
    expected = target_str.split(" = ")[-1].strip().strip("'\"")

    prompt = (
        f"{_INSTR}\n\n"
        f"Dictionary:\n{sample.prompt}\n\n"
        f"Starting hash: {query}\n"
        f"Final hash:"
    )
    return prompt, query, expected


def _extract_pred(out: str, exclude: str = "") -> str:
    """Pull the terminal 16-char hash from the model's output.

    The model often echoes the start hash before its answer ("KEY = VALUE", the
    dataset's own completion format), so taking the FIRST 16-char run returned
    the input hash and scored a correct answer wrong. Prefer a run that is not
    the known input hash, and take the last such run."""
    out = strip_to_final_channel(out)
    runs = re.findall(r"[A-Za-z]{16}", out)
    if not runs:
        return out.strip()
    if exclude:
        non_echo = [r for r in runs if r != exclude]
        if non_echo:
            return non_echo[-1]
    return runs[-1]


def evaluate_hashhop(
    model_path: str,
    n_per_hops: int = _INSTANCES_PER_HOP,
    hops_list: tuple[int, ...] = _DEFAULT_HOPS,
    chars_per_problem: int = _DEFAULT_CHARS,
    max_new_tokens: int = _MAX_NEW_TOKENS,
    seed: int = 42,
    reasoning: bool = False,
    repetition_penalty: float | None = None,
) -> HashHopResult:
    """Run HashHop and return per-hop + overall accuracy.

    Args:
        model_path: Path or HF repo of the MLX model.
        n_per_hops: Instances per hop count (default 25).
        hops_list: Hop counts to evaluate (default 1..4).
        chars_per_problem: Dictionary size in characters. With
            ``hash_pair_str_length=16``, ~12000 chars renders to roughly
            8-9k tokens after tokenization plus chat-template overhead.
        max_new_tokens: Generation budget per instance (a 16-char hash
            is ~5-6 tokens; 32 is conservative).
        seed: Reproducibility for sampling and chain generation.
    """
    from hashhop.generate import MultiHopEval
    from mlx_lm import load, generate
    from .decode import load_tolerant, reclaim, resolve_decode, seed_rng
    from tqdm import tqdm

    t0 = time.time()
    if os.path.isdir(model_path):
        model_path = os.path.abspath(model_path)
    print(f"  Loading model from {model_path} …")
    seed_rng(seed)   # diffusion decode starts from a RANDOM canvas
    model, tokenizer = load_tolerant(model_path)

    use_chat = bool(getattr(tokenizer, "chat_template", None))
    concise = {} if reasoning else concise_template_kwargs(tokenizer)
    # Reasoning models (gpt-oss) still emit a short analysis/commentary channel
    # before the final answer even at low effort, so a 32-token budget truncates
    # before the hash ever appears. Give them room; direct-answer models stop at
    # EOS well before the cap, so this doesn't change their results. In full
    # reasoning mode the caller supplies a large budget for the think trace.
    if concise or reasoning:
        max_new_tokens = max(max_new_tokens, 256)
    sampler, logits_processors = resolve_decode(model, repetition_penalty)

    random.seed(seed)
    np.random.seed(seed)

    results_by_hops: dict[int, dict] = {h: {"n": 0, "correct": 0} for h in hops_list}
    total_n = total_correct = 0
    sample_ctx_tokens: list[int] = []

    for hops in hops_list:
        for _ in tqdm(range(n_per_hops), desc=f"HashHop hops={hops}"):
            sample = MultiHopEval.make_one(
                n_chars_problem=chars_per_problem,
                num_queries=1,
                hops=hops,
                hash_pair_str_length=_HASH_LEN,
                chain_of_thought=False,
            )
            prompt_text, query, expected = _format_prompt(sample)

            if use_chat:
                try:
                    prompt = tokenizer.apply_chat_template(
                        [{"role": "user", "content": prompt_text}],
                        add_generation_prompt=True,
                        tokenize=False, **concise,
                    )
                except Exception:
                    prompt = prompt_text
            else:
                prompt = prompt_text

            if len(sample_ctx_tokens) < 5:
                sample_ctx_tokens.append(len(tokenizer.encode(prompt)))

            out = generate(
                model, tokenizer, prompt=prompt,
                max_tokens=max_new_tokens,
                sampler=sampler, logits_processors=logits_processors, verbose=False,
            )
            reclaim()
            pred = _extract_pred(out, exclude=query)
            ok = (pred == expected)
            results_by_hops[hops]["n"] += 1
            results_by_hops[hops]["correct"] += int(ok)
            total_n += 1
            total_correct += int(ok)

    elapsed = time.time() - t0
    by_hops = {
        h: v["correct"] / max(v["n"], 1)
        for h, v in results_by_hops.items()
    }
    overall = total_correct / max(total_n, 1)
    avg_ctx = (
        sum(sample_ctx_tokens) / len(sample_ctx_tokens)
        if sample_ctx_tokens else 0
    )

    return HashHopResult(
        overall_acc=overall,
        by_hops=by_hops,
        n_per_hops=n_per_hops,
        hops_list=tuple(hops_list),
        chars_per_problem=chars_per_problem,
        context_tokens_observed=int(avg_ctx),
        elapsed_sec=elapsed,
    )
